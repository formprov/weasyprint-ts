test('embedding levels match fribidi', () => {
  for (const [text, base, want] of CASES) {
    const cps = text.split(' ').map((h) => parseInt(h, 16));
    assert.equal(Array.from(embeddingLevels(cps, base)).join(''), want, `${text} (base ${base})`);
  }
});

test('fribidi FSI scan runs past the matching PDI', () => {
  // FSI [ PDI RLI HEBREW: fribidi resolves the FSI as RTL from the Hebrew letter after its PDI.
  assert.equal(Array.from(embeddingLevels([0x2068, 0x5b, 0x2069, 0x2067, 0x5d0], 1)).join(''), '13113');
});
