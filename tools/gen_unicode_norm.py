#!/usr/bin/env python3
"""Generate src/text/unicode_norm.ts from Python's unicodedata.

HarfBuzz's default normalizer (hb-ot-shape-normalize.cc) fully decomposes each
character, reorders combining marks by canonical combining class, then
recomposes base+mark pairs whenever the font has the composed glyph. Its
composition step uses the canonical decompositions from UnicodeData.txt
*without* applying CompositionExclusions.txt: shaping U+05E9 U+05C1 with
Arial produces the `shinshindot` glyph (U+FB2A), which plain NFC refuses to
compose. This table therefore contains every canonical two-codepoint
decomposition, exclusions included.

Run from weasyprint-ts/:  python3 tools/gen_unicode_norm.py
"""
import sys
import unicodedata

CCC = []      # (start, end, ccc) runs
DECOMP = []   # (cp, first, second-or-0) canonical decompositions
COMPOSE = {}  # (first, second) -> cp


def main():
    ccc_start = None
    ccc_value = 0
    for cp in range(0x110000):
        value = unicodedata.combining(chr(cp))
        if value != ccc_value:
            if ccc_value:
                CCC.append((ccc_start, cp - 1, ccc_value))
            ccc_start, ccc_value = cp, value
    if ccc_value:
        CCC.append((ccc_start, 0x10FFFF, ccc_value))

    for cp in range(0x110000):
        ch = chr(cp)
        raw = unicodedata.decomposition(ch)
        if not raw or raw.startswith('<'):
            continue  # compatibility mapping
        parts = [int(x, 16) for x in raw.split()]
        if not 1 <= len(parts) <= 2:
            continue
        DECOMP.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
        if len(parts) == 2:
            COMPOSE[(parts[0], parts[1])] = cp

    out = [
        '// SPDX-License-Identifier: BSD-3-Clause',
        '',
        '// Generated by tools/gen_unicode_norm.py from Python ' + sys.version.split()[0]
        + ' unicodedata (Unicode ' + unicodedata.unidata_version + '). Do not edit.',
        '',
        '/** Canonical combining classes: [start, end, class, ...]. */',
        'export const CCC_RANGES = new Uint32Array([' + ', '.join(
            str(x) for run in CCC for x in run) + ']);',
        '',
        '/** Canonical decompositions: [cp, first, second, ...] (second 0 for singletons). */',
        'export const DECOMP = new Uint32Array([' + ', '.join(
            str(x) for row in DECOMP for x in row) + ']);',
        '',
        '/** Canonical compositions, CompositionExclusions included: [first, second, cp, ...]. */',
        'export const COMPOSE = new Uint32Array([' + ', '.join(
            str(x) for (a, b), cp in sorted(COMPOSE.items()) for x in (a, b, cp)) + ']);',
        '',
    ]
    with open('src/text/unicode_norm.ts', 'w') as handle:
        handle.write('\n'.join(out))
    print(f'{len(CCC)} ccc runs, {len(DECOMP)} decompositions, {len(COMPOSE)} compositions')


if __name__ == '__main__':
    main()
