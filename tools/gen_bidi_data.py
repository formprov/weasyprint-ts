"""Generate src/text/bidi_data.ts from the oracle's own libfribidi (the library Pango uses), so bidi classes,
paired brackets and mirroring glyphs match the reference renderer exactly.

  docker run --rm -v "$PWD/tools:/t:ro" weasy-alpine-prod:latest /venv/bin/python /t/gen_bidi_data.py dump > /tmp/bidi.json
  python3 tools/gen_bidi_data.py emit /tmp/bidi.json > src/text/bidi_data.ts
"""
import json
import sys


def dump():
    import ctypes
    f = ctypes.CDLL('libfribidi.so.0')
    f.fribidi_get_bidi_type.restype = ctypes.c_uint32
    f.fribidi_get_bidi_type_name.restype = ctypes.c_char_p
    f.fribidi_get_bracket.restype = ctypes.c_uint32
    names, ranges, prev = {}, [], None
    for cp in range(0x110000):
        t = f.fribidi_get_bidi_type(cp)
        if t not in names:
            names[t] = f.fribidi_get_bidi_type_name(t).decode()
        n = names[t]
        if prev and prev[2] == n and prev[1] == cp - 1:
            prev[1] = cp
        else:
            prev = [cp, cp, n]
            ranges.append(prev)
    mirror, brackets, m = {}, {}, ctypes.c_uint32()
    for cp in range(0x110000):
        if f.fribidi_get_mirror_char(cp, ctypes.byref(m)):
            mirror[cp] = m.value
        b = f.fribidi_get_bracket(cp)
        if b:
            brackets[cp] = [b & 0x7fffffff, 1 if b & 0x80000000 else 0]
    print(json.dumps(dict(ranges=ranges, mirror=mirror, brackets=brackets)))


# fribidi type names -> UAX #9 short names.
NAMES = {'LTR': 'L', 'RTL': 'R', 'AL': 'AL', 'EN': 'EN', 'AN': 'AN', 'ES': 'ES', 'ET': 'ET', 'CS': 'CS', 'NSM': 'NSM',
         'BN': 'BN', 'BS': 'B', 'SS': 'S', 'WS': 'WS', 'ON': 'ON', 'LRE': 'LRE', 'RLE': 'RLE', 'LRO': 'LRO',
         'RLO': 'RLO', 'PDF': 'PDF', 'LRI': 'LRI', 'RLI': 'RLI', 'FSI': 'FSI', 'PDI': 'PDI'}
CLASSES = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON',
           'LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI']


def emit(path):
    d = json.load(open(path))
    rows = []
    for start, end, name in d['ranges']:
        cls = NAMES[name]
        if cls == 'L':
            continue  # default
        rows.append(f'{start:x},{end - start + 1:x},{CLASSES.index(cls):x}')
    mirror = ';'.join(f'{int(k):x},{v:x}' for k, v in sorted(d['mirror'].items(), key=lambda kv: int(kv[0])))
    brackets = ';'.join(f'{int(k):x},{v[0]:x},{v[1]}' for k, v in sorted(d['brackets'].items(), key=lambda kv: int(kv[0])))
    out = sys.stdout
    out.write('// SPDX-License-Identifier: BSD-3-Clause\n\n')
    out.write('// GENERATED by tools/gen_bidi_data.py from the oracle\'s libfribidi 1.0.16. Do not edit.\n\n')
    out.write(f'export const BIDI_CLASSES = {json.dumps(CLASSES)} as const;\n\n')
    out.write('/** Non-L ranges as hex `start,length,classIndex`, sorted by start; every other code point is L. */\n')
    out.write(f"export const BIDI_RANGES = '{';'.join(rows)}';\n\n")
    out.write('/** Bidi_Mirroring_Glyph pairs as hex `cp,mirror`. */\n')
    out.write(f"export const BIDI_MIRRORS = '{mirror}';\n\n")
    out.write('/** Paired brackets as hex `cp,openingBracket,isOpen`. */\n')
    out.write(f"export const BIDI_BRACKETS = '{brackets}';\n")


if __name__ == '__main__':
    dump() if sys.argv[1] == 'dump' else emit(sys.argv[2])
